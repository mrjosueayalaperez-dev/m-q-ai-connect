package com.mq.crm.auth

import java.security.KeyStore
import java.util.Base64
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/** Where the session token lives on the device. */
interface TokenStore {
    fun load(): String?
    fun save(token: String)
    fun clear()
}

/** Minimal key-value storage (SharedPreferences on device, a map in tests). */
interface KeyValue {
    fun get(key: String): String?
    fun put(key: String, value: String)
    fun remove(key: String)
}

/**
 * AES-256-GCM sealing of the token. Output: "v1:<iv b64>:<ciphertext+tag b64>".
 * A fresh 12-byte IV per seal (generated by the cipher); the tag authenticates
 * the ciphertext, so a tampered value fails to open and is discarded.
 */
class AesGcmCodec(private val key: () -> SecretKey) {
    fun seal(plain: String): String {
        val c = Cipher.getInstance(TRANSFORMATION)
        c.init(Cipher.ENCRYPT_MODE, key())
        val ct = c.doFinal(plain.toByteArray(Charsets.UTF_8))
        val b64 = Base64.getEncoder()
        return "v1:" + b64.encodeToString(c.iv) + ":" + b64.encodeToString(ct)
    }

    fun open(sealed: String): String? = try {
        val parts = sealed.split(":")
        if (parts.size != 3 || parts[0] != "v1") null
        else {
            val b64 = Base64.getDecoder()
            val c = Cipher.getInstance(TRANSFORMATION)
            c.init(Cipher.DECRYPT_MODE, key(), GCMParameterSpec(128, b64.decode(parts[1])))
            String(c.doFinal(b64.decode(parts[2])), Charsets.UTF_8)
        }
    } catch (e: Exception) {
        null // wrong key, tampered or corrupt: treat as signed out
    }

    companion object {
        const val TRANSFORMATION = "AES/GCM/NoPadding"
    }
}

/** Token sealed with [codec] and kept in [kv]. Only ciphertext is stored. */
class EncryptedTokenStore(private val kv: KeyValue, private val codec: AesGcmCodec) : TokenStore {
    override fun load(): String? {
        val sealed = kv.get(KEY) ?: return null
        val t = codec.open(sealed)
        if (t == null) kv.remove(KEY)
        return t
    }

    override fun save(token: String) = kv.put(KEY, codec.seal(token))
    override fun clear() = kv.remove(KEY)

    companion object {
        const val KEY = "session_token_v1"
    }
}

/**
 * The device key: AES-256 generated INSIDE the Android Keystore
 * ("AndroidKeyStore"), non-exportable, usable only for AES/GCM. The key
 * material never enters app memory or app storage.
 */
object AndroidKeystoreKey {
    const val ALIAS = "mq_crm_session_token_key"
    private const val PROVIDER = "AndroidKeyStore"

    fun getOrCreate(): SecretKey {
        val ks = KeyStore.getInstance(PROVIDER).apply { load(null) }
        (ks.getEntry(ALIAS, null) as? KeyStore.SecretKeyEntry)?.let { return it.secretKey }
        val gen = KeyGenerator.getInstance(android.security.keystore.KeyProperties.KEY_ALGORITHM_AES, PROVIDER)
        gen.init(
            android.security.keystore.KeyGenParameterSpec.Builder(
                ALIAS,
                android.security.keystore.KeyProperties.PURPOSE_ENCRYPT or
                    android.security.keystore.KeyProperties.PURPOSE_DECRYPT,
            )
                .setBlockModes(android.security.keystore.KeyProperties.BLOCK_MODE_GCM)
                .setEncryptionPaddings(android.security.keystore.KeyProperties.ENCRYPTION_PADDING_NONE)
                .setKeySize(256)
                .setRandomizedEncryptionRequired(true)
                .build()
        )
        return gen.generateKey()
    }
}
